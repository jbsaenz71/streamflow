"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# AI WROTE THE CODE. AI HELPED ME UNDERSTAND THE CODE.
# I define the beam variables. Some variables include reaction forces and
# the length of the beam which will be important when calculating the
# shear and moment equations for their respective diagrams.
L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

# I used linespace to create 500, equally spaced segments for the entire length of the beam.
x = np.linspace(0, L, 500)

# I create an array of zeros for to input the calculated shear forces
V = np.zeros_like(x)

# I use a for loop to calculate the shear force at each position. The results
# are then stored in the the array "V" I defined earlier.
for i in range(len(x)):

    if x[i] < 2:
        V[i] = RA - (q1 * x[i])

    elif x[i] < 4:
        V[i] = RA - (q1 * 2) - P1

    else:
        V[i] = RA - (q1 * 2) - P1 + RB - (q2 * (x[i] - 4))

# I create the shear diagram. The line will be green.
plt.plot(x, V, color='green')

# I use this command to shade the area between the shear line and zero
plt.fill_between(x, V, 0, color='lightgreen', alpha=0.5)

# I add a horizontal line at zero to show the shear force at the many points
# along the length of the beam
plt.axhline(y=0, color='black')

# I add a title and labels to the x and y axes
plt.title('Shear Force Diagram')
plt.xlabel('Distance Along Beam (ft)')
plt.ylabel('Shear Force (lb)')

# I add gridlines
plt.grid(True)

# I display the graph
plt.show()

